// Create a chapter file on demand (a chapter whose title matches no
// existing file — e.g. clicked in the chapter panel before any note was
// written for it). Idempotent: an existing chapter for the title/page is
// returned as-is. The number is max+1, so the file name never collides.
app.post('/api/projects/:slug/chapters', async (req, res, next) => {
  try {
    const { title, page } = req.body ?? {};
    if (typeof title !== 'string' || !title.trim()) {
      return res.status(400).json({ error: 'title (string) is required' });
    }
    const pageNum = page === undefined || page === null ? null : page;
    if (pageNum !== null && (!Number.isInteger(pageNum) || pageNum < 1)) {
      return res.status(400).json({ error: 'page must be a positive integer or null' });
    }
    const project = await readProject(req.params.slug);
    await ensureChapterLayout(req.params.slug, project);
    let chapters = await getChapters(req.params.slug);
    const existing = resolveChapter(chapters, { title: title.trim(), page: pageNum });
    if (existing) return res.json({ chapter: existing, chapters });
    const notesDir = resolveProjectPath(DATA_DIR, req.params.slug, 'notes');
    await fsp.mkdir(notesDir, { recursive: true });
    let number = chapters.reduce((m, c) => Math.max(m, c.number), 0) + 1;
    let file = chapterFileName({ number, title: title.trim() });
    while (true) {
      try {
        await fsp.stat(path.join(notesDir, file));
        file = chapterFileName({ number: ++number, title: title.trim() });
      } catch {
        break; // free
      }
    }
    const content = buildChapterFile({ heading: title.trim(), page: pageNum, body: '' });
    await fsp.writeFile(path.join(notesDir, file), content, 'utf8');
    await regenerateIndex(req.params.slug, project);
    chapters = await getChapters(req.params.slug);
    res.status(201).json({ chapter: chapters.find((c) => c.file === file), chapters });
  } catch (err) {
    if (err.code === 'ENOENT') return res.status(404).json({ error: 'project not found' });
    next(err);
  }
});

