function projectsDir() {
  return path.join(DATA_DIR, 'projects');
}

async function readProject(slug) {
  const file = resolveProjectPath(DATA_DIR, slug, 'project.json');
  const raw = await fsp.readFile(file, 'utf8');
  return JSON.parse(raw);
}

async function writeProject(slug, project) {
  const file = resolveProjectPath(DATA_DIR, slug, 'project.json');
  project.updatedAt = new Date().toISOString();
  await fsp.writeFile(file, JSON.stringify(project, null, 2) + '\n', 'utf8');
  return project;
}

async function listNoteFiles(slug) {
  const dir = resolveProjectPath(DATA_DIR, slug, 'notes');
  try {
    const entries = await fsp.readdir(dir, { withFileTypes: true });
    return entries
      .filter((e) => e.isFile() && /\.(md|ipynb)$/i.test(e.name) && e.name !== INDEX_FILE)
      .map((e) => e.name)
      .sort();
  } catch {
    return [];
  }
}

// ---------------------------------------------------------------------------
// Per-chapter note files + the app-maintained master index (see
// src/chapterNotes.js). Notes live in `notes/chapter-NN-slug.md`, one file
// per chapter; `notes/index.md` is generated by the app (title + byline +
// hyperlinks to each chapter file and its labs), never hand-edited.
// A legacy single `notes.md` is split once, on first load after the
// upgrade (or via POST .../notes/migrate); the original file is kept as
// `notes.md.migrated` and its header stored verbatim in
// project.json `notesHeader` so the single-file export reconstructs it.
// ---------------------------------------------------------------------------

/** Chapter files on disk, in reading order: [{number, title, page, file, labs}]. */
async function getChapters(slug) {
  const dir = resolveProjectPath(DATA_DIR, slug, 'notes');
  let names;
  try {
    names = (await fsp.readdir(dir)).filter((n) => isChapterFile(n)).sort();
  } catch {
    return [];
  }
  const labs = await listLabs(slug);
  const labsByGroup = new Map(labs.chapters.map((g) => [g.chapter, g.files]));
  const out = [];
  for (const name of names) {
    const parsed = parseChapterFileName(name);
    let content;
    try {
      content = await fsp.readFile(path.join(dir, name), 'utf8');
    } catch {
      continue;
    }
    const m = content.match(/^##\s+(.+?)\s*#*\s*$/m);
    const title = m ? m[1].trim() : parsed.slug.replace(/-/g, ' ');
    const group = labGroupForChapterNumber(parsed.number);
    out.push({
      number: parsed.number,
      title,
      page: extractPageNumber(content),
      file: name,
      labs: (labsByGroup.get(group) ?? []).map((f) => ({ name: f.name, path: f.path })),
    });
  }
  // Book order when pages are known, else file-number order.
  out.sort((a, b) => (a.page ?? Infinity) - (b.page ?? Infinity) || a.number - b.number);
  return out;
}

/** Regenerate notes/index.md from the chapter files (no-op when unchanged). */
async function regenerateIndex(slug, project) {
  const chapters = await getChapters(slug);
  const text = composeIndex({
    title: project.title,
    byline: bylineFromHeader(project.notesHeader ?? ''),
    chapters,
  });
  const file = resolveProjectPath(DATA_DIR, slug, 'notes', INDEX_FILE);
  let current = null;
  try {
    current = await fsp.readFile(file, 'utf8');
  } catch {
    // Missing — write below.
  }
  if (current !== text) {
    await fsp.mkdir(path.dirname(file), { recursive: true });
    await fsp.writeFile(file, text, 'utf8');
  }
  return { text, chapters };
}

/** Write per-chapter files for `sections` (from splitNotesMd). Returns the file names. */
async function writeChapterFiles(slug, sections, labsByGroup = new Map()) {
  const notesDir = resolveProjectPath(DATA_DIR, slug, 'notes');
  const used = new Set();
  const files = [];
  for (const s of sections) {
    let file = chapterFileName({ number: s.number, title: s.heading });
    let n = 2;
    while (used.has(file)) file = chapterFileName({ number: s.number, title: `${s.heading} ${n++}` });
    used.add(file);
    const groupLabs = labsByGroup.get(labGroupForChapterNumber(s.number)) ?? [];
    await fsp.writeFile(
      path.join(notesDir, file),
      refreshLabsBlock(s.raw, groupLabs, s.number),
      'utf8',
    );
    files.push(file);
  }
  return files;
}

/**
 * Split a legacy notes.md into per-chapter files. Runs once: only when
 * notes.md exists AND no chapter files exist yet. The header is stored
 * verbatim in project.json `notesHeader`; the legacy file is renamed to
 * notes.md.migrated (kept as a backup). Returns true when it migrated.
 * Never throws — a failed migration leaves the legacy file in place and
 * the caller carries on with it.
 */
async function migrateLegacyNotes(slug, project) {
  try {
    const notesDir = resolveProjectPath(DATA_DIR, slug, 'notes');
    const legacy = path.join(notesDir, LEGACY_NOTES_FILE);
    let text;
    try {
      text = await fsp.readFile(legacy, 'utf8');
    } catch {
      return false; // no legacy file — nothing to migrate
    }
    if ((await getChapters(slug)).length) return false; // already migrated
    const { header, sections } = splitNotesMd(text);
    const labs = await listLabs(slug);
    const labsByGroup = new Map(labs.chapters.map((g) => [g.chapter, g.files]));
    if (!sections.length) {
      // No `##` headings at all: the whole file (minus its `#` title) is
      // one chapter, "Notes" — user content is never stranded. (The export
      // then carries the added `## Notes` heading; that is the one place
      // the round-trip is not byte-exact.)
      const { titlePart, rest } = splitHeaderTitle(header);
      const body = rest ? `${rest.replace(/\s+$/, '')}\n` : '';
      const file = 'chapter-01-notes.md';
      await fsp.writeFile(
        path.join(notesDir, file),
        refreshLabsBlock(buildChapterFile({ heading: 'Notes', page: null, body }), [], 1),
        'utf8',
      );
      project.notesHeader = titlePart;
    } else {
      await writeChapterFiles(slug, sections, labsByGroup);
      project.notesHeader = header;
    }
    await writeProject(slug, project);
    await fsp.rename(legacy, path.join(notesDir, MIGRATED_BACKUP_FILE));
    await regenerateIndex(slug, project);
    return true;
  } catch (err) {
    console.error(`chapter-notes migration failed for ${slug}:`, err.message);
    return false;
  }
}

/** Migrate a legacy notes.md when present; (re)create the index when chapters exist but it is missing. */
async function ensureChapterLayout(slug, project) {
  await migrateLegacyNotes(slug, project);
  const chapters = await getChapters(slug);
  if (chapters.length) {
    try {
      await fsp.stat(resolveProjectPath(DATA_DIR, slug, 'notes', INDEX_FILE));
    } catch {
      try {
        await regenerateIndex(slug, project);
      } catch {
        // The index is derived; never fail a read over it.
      }
    }
  }
  return chapters;
}

/**
 * The user's notes for a chapter title — read from that chapter's file
 * (Labs block stripped), falling back to a legacy notes.md that has not
 * migrated yet. Used by ai-note's "Include my notes".
 */
async function readChapterNoteSection(slug, chapterTitle) {
  const chapters = await getChapters(slug);
  const entry = resolveChapter(chapters, { title: chapterTitle });
  if (entry) {
    try {
      const content = await fsp.readFile(
        resolveProjectPath(DATA_DIR, slug, 'notes', entry.file), 'utf8');
      return extractChapterSection(stripLabsBlock(content), chapterTitle);
    } catch {
      return '';
    }
  }
  try {
    const notes = await fsp.readFile(
      resolveProjectPath(DATA_DIR, slug, 'notes', LEGACY_NOTES_FILE), 'utf8');
    return extractChapterSection(notes, chapterTitle);
  } catch {
    return '';
  }
}

