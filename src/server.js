// One-click export: all chapters in order as a single .md, equivalent to
// the old notes.md shape (`##` headings + `<!-- p. N -->` comments +
// anchors; the generated Labs blocks are stripped). Standalone notes
// (files that are not chapter files) are not chapters and are excluded.
app.get('/api/projects/:slug/notes/export', async (req, res, next) => {
  try {
    const project = await readProject(req.params.slug);
    const chapters = await ensureChapterLayout(req.params.slug, project);
    const chapterContents = [];
    for (const ch of chapters) {
      const content = await fsp.readFile(
        resolveProjectPath(DATA_DIR, req.params.slug, 'notes', ch.file), 'utf8');
      chapterContents.push({ content });
    }
    const text = composeCombined({
      notesHeader: project.notesHeader ?? '',
      chapterContents,
    });
    res.setHeader('Content-Type', 'text/markdown; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${req.params.slug}-notes.md"`);
    res.send(text);
  } catch (err) {
    if (err.code === 'ENOENT') return res.status(404).json({ error: 'project not found' });
    next(err);
  }
});

app.get('/api/projects/:slug/file', async (req, res, next) => {
  try {
    const project = await readProject(req.params.slug);
    if (project.sourceType === 'url') {
      if (!project.sourceUrl) return res.status(404).json({ error: 'no source URL' });
      return res.redirect(302, project.sourceUrl);
    }
    if (!project.file) return res.status(404).json({ error: 'no source file' });
    const filePath = resolveProjectPath(DATA_DIR, req.params.slug, project.file);
    await fsp.stat(filePath); // 404 when the file is gone
    // res.sendFile honours Range requests, which pdf.js needs.
    res.sendFile(filePath);
  } catch (err) {
    if (err.code === 'ENOENT') return res.status(404).json({ error: 'project or file not found' });
    next(err);
  }
});

