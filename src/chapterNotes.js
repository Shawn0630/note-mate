// Per-chapter note files + the app-maintained master index.
//
// The redesign (2026-11-11, user decision): the user never maintains a
// master markdown. Notes live in ONE FILE PER CHAPTER —
// `notes/chapter-NN-slug.md` — and the app owns a master index,
// `notes/index.md`, with hyperlinks to each chapter file (+ page + labs).
//
// Why files, not headings: the old layout kept all chapters in one
// `notes.md` and resolved chapters by `##`-heading index (chapterMap).
// Any `###` sub-heading inserted mid-file shifted every later chapter's
// index — the fragility this module kills structurally. A `###` inside a
// chapter file can never shift another chapter, because chapters are
// files, not positions in a shared file.
//
// Naming: `chapter-NN-slug.md`, NN = the chapter number (from the `##`
// heading's leading number, else the 1-based position among `##`
// headings), slug = slugify of the normalized heading text. E.g.
// `chapter-02-supervised-learning.md`.
//
// Master index: a SEPARATE `notes/index.md` (not `notes.md` — that name
// is the legacy single file, kept as `notes.md.migrated` after migration).
// The index is generated by the app, excluded from the note tabs, and
// PUT-rejected. It lists each chapter (title + page) with a relative
// link to its file, plus per-chapter exercise links. It is regenerated
// on chapter-file writes, migration, seed, and AI import, and on read
// when missing.
//
// Chapter files also carry a generated `### Labs` block (marked with
// `<!-- labs:start -->` / `<!-- labs:end -->`), listing that chapter's
// coding-exercise labs as relative links. The block is app-maintained
// chrome, not note content: user content always inserts BEFORE it, and
// the single-file export strips it, so split → export round-trips the
// original `notes.md` byte-for-byte.
//
// Pure functions — no I/O, no Express. Unit-tested in
// tests/chapterNotes.test.js.
import { normalizeHeading, slugify } from './util.js';

export const INDEX_FILE = 'index.md';
export const LEGACY_NOTES_FILE = 'notes.md';
export const MIGRATED_BACKUP_FILE = 'notes.md.migrated';
export const LABS_START = '<!-- labs:start -->';
export const LABS_END = '<!-- labs:end -->';

const CHAPTER_FILE_RE = /^chapter-(\d+)-(.+)\.md$/i;

/** `chapter-02-supervised-learning.md` from {number: 2, title: 'Supervised learning'}. */
export function chapterFileName({ number, title }) {
  const n = Number.isInteger(number) && number >= 1 ? number : 1;
  const slug = slugify(normalizeHeading(title) || title) || 'notes';
  return `chapter-${String(n).padStart(2, '0')}-${slug}.md`;
}

/** Parse the chapter number from a heading: "12. Transformers" -> 12. */
export function parseChapterNumber(headingText) {
  const m = String(headingText ?? '').match(/^\s*(\d+)\s*[.)]\s/);
  return m ? Number(m[1]) : null;
}

/** "Chap01" -> "Chapter 1"; anything else is shown as-is. */
export function chapterDisplayName(chapter) {
  const m = String(chapter ?? '').match(/(\d+)/);
  return m ? `Chapter ${Number(m[1])}` : String(chapter ?? '');
}

/** The lab group dir for a chapter number: chapter 12 -> "Chap12". */
export function labGroupForChapterNumber(n) {
  return n == null ? null : `Chap${String(n).padStart(2, '0')}`;
}

/** "1_1_BackgroundMathematics.ipynb" -> "1.1 Background Mathematics". */
export function labDisplayName(name) {
  const base = String(name ?? '').replace(/\.ipynb$/i, '');
  const m = base.match(/^(\d+)_(\d+)_(.+)$/);
  if (m) {
    const title = m[3].replace(/_/g, ' ')
      .replace(/([a-z0-9])([A-Z])/g, '$1 $2').trim();
    return `${m[1]}.${m[2]} ${title}`;
  }
  return base.replace(/_/g, ' ');
}

/**
 * The page number a chapter starts on, from the `<!-- p. N -->` comment
 * the seed writes under each `##` heading (or the `<!-- @page N · source:
 * book -->` anchor form). Null when the file carries no page comment.
 */
export function extractPageNumber(text) {
  const t = String(text ?? '');
  let m = t.match(/<!--\s*p\.\s*(\d+)\s*-->/);
  if (m) return Number(m[1]);
  m = t.match(/<!--\s*@page\s+(\d+)\s*·\s*source:\s*book\s*-->/);
  return m ? Number(m[1]) : null;
}

/**
 * Split a legacy single-file `notes.md` into its header + `##` sections.
 * Returns `{header, sections: [{heading, page, number, raw}]}` where `raw`
 * is the EXACT slice of the original text (heading line through the line
 * before the next `##` heading, or EOF), so `header +
 * sections.map(s => s.raw).join('')` is the original text byte-for-byte.
 * `##` lines inside fenced code blocks do not split (a note's code sample
 * must never become a chapter). `###` sub-headings never split either.
 */
export function splitNotesMd(text) {
  const src = String(text ?? '');
  const lines = src.split('\n');
  // Byte offsets of each line start, so slices are exact.
  const offsets = [0];
  for (let i = 0; i < lines.length; i++) offsets.push(offsets[i] + lines[i].length + 1);
  const headingLines = [];
  let inFence = false;
  lines.forEach((line, i) => {
    if (/^\s*```/.test(line)) inFence = !inFence;
    if (inFence) return;
    const m = line.match(/^##\s+(.+?)\s*#*\s*$/);
    if (m) headingLines.push({ line: i, heading: m[1].trim() });
  });
  const header = headingLines.length ? src.slice(0, offsets[headingLines[0].line]) : src;
  const sections = headingLines.map((h, i) => {
    const start = offsets[h.line];
    const end = i + 1 < headingLines.length ? offsets[headingLines[i + 1].line] : src.length;
    const raw = src.slice(start, end);
    return {
      heading: h.heading,
      page: extractPageNumber(raw),
      number: parseChapterNumber(h.heading) ?? (i + 1),
      raw,
    };
  });
  return { header, sections };
}

/**
 * Build a chapter file from parts (seed / on-demand creation):
 * its own `##` heading, the `<!-- p. N -->` comment, then the body.
 */
export function buildChapterFile({ heading, page, body = '' }) {
  const head = `## ${heading}\n${Number.isInteger(page) && page >= 1 ? `<!-- p. ${page} -->\n` : ''}`;
  const b = String(body ?? '');
  if (!b) return head;
  return `${head}\n${b.startsWith('\n') ? b.slice(1) : b}`;
}

/** The generated Labs block for a chapter's labs ([{name, path}]). */
export function labsBlock(labs, chapterNumber) {
  const group = labGroupForChapterNumber(chapterNumber);
  const items = (labs ?? []).map((l) => `- [${labDisplayName(l.name)}](${l.path})`);
  if (!items.length) return '';
  return `${LABS_START}\n### Labs\n\n${items.join('\n')}\n${LABS_END}`;
}

/**
 * Strip the generated Labs block from chapter-file text. The block is
 * appended as "\n" + block + "\n" (see refreshLabsBlock), so stripping
 * removes exactly that envelope and returns the pre-block text verbatim.
 */
export function stripLabsBlock(text) {
  const src = String(text ?? '');
  const start = src.indexOf(`\n${LABS_START}`);
  if (start === -1) return src;
  const endMarker = src.indexOf(LABS_END, start);
  if (endMarker === -1) return src;
  let end = endMarker + LABS_END.length;
  if (src[end] === '\n') end += 1;
  return src.slice(0, start) + src.slice(end);
}

/**
 * Refresh the generated Labs block in chapter-file text: append it when
 * the chapter has labs and no block exists, replace it when the lab list
 * changed, remove it when the chapter has no labs. User content outside
 * the block is never touched; returns the text unchanged when nothing
 * changed (so a PUT that only refreshes does not rewrite the file).
 */
export function refreshLabsBlock(text, labs, chapterNumber) {
  const src = String(text ?? '');
  const block = labsBlock(labs, chapterNumber);
  const start = src.indexOf(`\n${LABS_START}`);
  if (start === -1) {
    if (!block) return src;
    const base = src.endsWith('\n') ? src : `${src}\n`;
    return `${base}\n${block}\n`;
  }
  const endMarker = src.indexOf(LABS_END, start);
  if (endMarker === -1) return src; // malformed block — leave it alone
  let end = endMarker + LABS_END.length;
  if (src[end] === '\n') end += 1;
  if (!block) return src.slice(0, start) + src.slice(end);
  const next = `${src.slice(0, start)}\n${block}\n${src.slice(end)}`;
  return next === src ? src : next;
}

/**
 * Append `block` (markdown) to a chapter file, idempotently: a second
 * append of the exact same block is a no-op (inserted: false). The block
 * lands BEFORE the generated Labs block when one exists (user content
 * stays above the app-maintained list), else at the end of the file.
 * The Labs block itself is never searched for duplicates — it is not
 * user content.
 */
export function appendToChapter(text, block) {
  const b = String(block ?? '').trim();
  if (!b) return { text: String(text ?? ''), inserted: false };
  const src = String(text ?? '');
  const userText = stripLabsBlock(src);
  if (userText.includes(b)) return { text: src, inserted: false };
  const marker = src.indexOf(LABS_START);
  if (marker === -1) {
    const base = src && !src.endsWith('\n') ? `${src}\n` : src;
    const sep = src && !src.endsWith('\n\n') ? '\n' : '';
    return { text: `${base}${sep}${b}\n`, inserted: true };
  }
  // Insert before the Labs block: keep everything up to the last
  // non-blank line before it, then the block, then the block.
  const before = src.slice(0, marker).replace(/\s+$/, '');
  const after = src.slice(marker);
  const sep = before ? '\n\n' : '';
  return { text: `${before}${sep}${b}\n\n${after}`, inserted: true };
}

/** The byline of a notes header: the header minus its `#` title line. */
export function bylineFromHeader(header) {
  const lines = String(header ?? '').split('\n');
  if (lines.length && /^#\s/.test(lines[0])) lines.shift();
  return lines.join('\n').trim();
}

/**
 * Split a notes header into its `#` title part (the title line plus the
 * blank lines after it) and the rest (the byline). Used when a legacy
 * file has no `##` headings at all: the title part stays the header and
 * the rest becomes the body of the single "Notes" chapter, so the
 * single-file export keeps the title once and the prose once.
 */
export function splitHeaderTitle(header) {
  const lines = String(header ?? '').split('\n');
  if (!lines.length || !/^#\s/.test(lines[0])) return { titlePart: '', rest: String(header ?? '') };
  let i = 1;
  while (i < lines.length && lines[i].trim() === '') i++;
  const titlePart = lines.slice(0, i).join('\n') + (i < lines.length ? '\n' : '');
  return { titlePart, rest: lines.slice(i).join('\n') };
}

/**
 * Compose the master index. `chapters` are [{number, title, page, file,
 * labs: [{name, path}]}] in order. Links are relative to notes/ so the
 * file stays portable; the app intercepts them in its previews.
 */
export function composeIndex({ title, byline, chapters }) {
  const lines = [
    '<!-- This index is maintained by Note Mate — edit the chapter files, not this file. -->',
    '',
    `# ${title || 'Notes'}`,
    '',
  ];
  const bl = String(byline ?? '').trim();
  if (bl) lines.push(bl, '');
  lines.push('## Chapters', '');
  for (const ch of chapters ?? []) {
    lines.push(`- [${ch.title}](${ch.file})${ch.page != null ? ` — p. ${ch.page}` : ''}`);
    if (ch.labs?.length) {
      const links = ch.labs.map((l) => `[${labDisplayName(l.name)}](${l.path})`).join(' · ');
      lines.push(`  - Exercises: ${links}`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Compose the single-file export from the stored header + the chapter
 * files' contents (Labs blocks stripped). Split → export round-trips
 * the original legacy `notes.md` byte-for-byte.
 */
export function composeCombined({ notesHeader, chapterContents }) {
  const header = String(notesHeader ?? '');
  const bodies = (chapterContents ?? []).map((c) => stripLabsBlock(c.content ?? '')).join('');
  return `${header}${bodies}`;
}

/**
 * Resolve an outline chapter ({title, page}) to a chapter entry.
 * Title match first (normalized — heading numbers are stripped, so
 * "12. Transformers" matches "Transformers"), then page match (so a
 * renamed heading still resolves by its `<!-- p. N -->` comment).
 */
export function resolveChapter(chapters, { title, page }) {
  const list = chapters ?? [];
  if (title) {
    const norm = normalizeHeading(title);
    if (norm) {
      const byTitle = list.find((c) => normalizeHeading(c.title) === norm);
      if (byTitle) return byTitle;
    }
  }
  if (Number.isInteger(page)) {
    const byPage = list.find((c) => c.page === page);
    if (byPage) return byPage;
  }
  return null;
}

/** Parse a chapter file name → {number, slug} or null. */
export function parseChapterFileName(name) {
  const m = String(name ?? '').match(CHAPTER_FILE_RE);
  return m ? { number: Number(m[1]), slug: m[2] } : null;
}

/** True when the name is a per-chapter file (not the index, not a lab). */
export function isChapterFile(name) {
  return CHAPTER_FILE_RE.test(String(name ?? ''));
}
